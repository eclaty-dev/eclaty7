var PAGES = ['accueil','apropos','produits','blog','contact'];
var CL = 'fr', CP = 'accueil';

function parseHash(){
  var h = location.hash.replace(/^#\/?/, '');
  var parts = h.split('/').filter(Boolean);
  var lang = 'fr', page = 'accueil';
  if(parts[0] && SLUGS[parts[0]]) lang = parts[0];
  if(parts[1] && SLUG_MAP[parts[1]]) page = SLUG_MAP[parts[1]];
  return {lang:lang, page:page};
}

function setHash(page, lang){
  var slug = SLUGS[lang][page];
  location.hash = '#/' + lang + '/' + slug;
}

function go(page, lang){
  if(lang) CL = lang;
  if(page) CP = page;
  setHash(CP, CL);
  render();
}

function render(){
  document.documentElement.lang = CL;
  document.getElementById('pg-title').textContent = T[CL].title;
  var md = document.getElementById('meta-desc');
  if(md) md.setAttribute('content', T[CL].desc);
  buildNav();
  buildPage();
  buildFooter();
  updateHreflang();
  window.scrollTo({top:0, behavior:'smooth'});
}

function updateHreflang(){
  var existing = document.querySelectorAll('link[rel="alternate"]');
  for(var i=0;i<existing.length;i++) existing[i].remove();
  var langs = ['fr','en','es'];
  for(var i=0;i<langs.length;i++){
    var l = document.createElement('link');
    l.rel = 'alternate'; l.hreflang = langs[i];
    l.href = location.origin + location.pathname + '#/' + langs[i] + '/' + SLUGS[langs[i]][CP];
    document.head.appendChild(l);
  }
}

